def T(zh, loc):
    man = MAN[loc]
    if zh in man: return man[zh]
    d = AR if loc == 'ar' else EN
    return d.get(zh) or zh

def emit(loc):
    out = [HEAD[loc]]
    for indent, label, kind, literal in TREE:
        text = fb_(label, loc) if literal else T(label, loc)
        if kind == 'h': out.append(f'\n## {text}\n')
        elif kind == 'page': out.append(f'\n### 📄 {text}\n')
        elif kind == 'sec': out.append(f"{'  ' * indent}- **{text}**")
        elif kind == 'opts': out.append(f"{'  ' * indent}  - *{text}*")
        else: out.append(f"{'  ' * indent}- {text}")
    p = os.path.join(ROOT, f'ui_blueprint_{loc}.md')
    with open(p, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print(p)

def fb_(key, loc):
    return MAN[loc][key]

emit('ar'); emit('en')
